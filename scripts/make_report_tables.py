"""Generate LaTeX tables / numbers for the report from the result CSVs.

    python scripts/make_report_tables.py        # -> report/generated.tex

Reads results/eval_summary.csv (held-out evaluation, see README) and
results/robustness.csv, so every number in the report is reproducible.
"""
from pathlib import Path

import pandas as pd

RES = Path("results")
OUT = Path("report/generated.tex")

LABEL = {
    "no_rebalancing": "No rebalancing",
    "threshold_default": "Threshold (default)",
    "threshold_tuned": "Threshold (tuned)",
    "ppo_v4": r"\textbf{PPO (ours)}",
    "ppo_v4_nomask": r"\quad no action mask",
    "ppo_v3": r"\quad absolute reward (v3)",
    "ppo_v2": r"\quad\ \ + amount actions (v2)",
    "ppo_v1": r"\quad\ \ + 4N+3 obs, const.\ LR (v1)",
}


def fmt_row(name, r, bold_best):
    def cell(col, f, best):
        v = f(r[(col, "mean")])
        return rf"\textbf{{{v}}}" if best else v
    return " & ".join([
        LABEL.get(name, name.replace("_", r"\_")),
        cell("ret", lambda x: f"{x:.1f}", bold_best.get("ret") == name),
        cell("service_rate", lambda x: f"{100 * x:.1f}", bold_best.get("service_rate") == name),
        cell("lost", lambda x: f"{x:.0f}", bold_best.get("lost") == name),
        cell("km", lambda x: f"{x:.0f}", False),
        cell("failed_docks", lambda x: f"{x:.0f}", bold_best.get("failed_docks") == name),
    ]) + r" \\"


def main():
    s = pd.read_csv(RES / "eval_summary.csv", header=[0, 1], index_col=0)
    main_rows = [p for p in ["no_rebalancing", "threshold_default", "threshold_tuned", "ppo_v4"] if p in s.index]
    abl_rows = [p for p in ["ppo_v4", "ppo_v4_nomask", "ppo_v3", "ppo_v2", "ppo_v1"] if p in s.index]
    best = {
        "ret": s.loc[main_rows, ("ret", "mean")].idxmax(),
        "service_rate": s.loc[main_rows, ("service_rate", "mean")].idxmax(),
        "lost": s.loc[main_rows, ("lost", "mean")].idxmin(),
        "failed_docks": s.loc[[p for p in main_rows if p != "no_rebalancing"], ("failed_docks", "mean")].idxmin(),
    }
    head = r"Policy & Return & Serv.\,\% & Lost & km & Full \\ \midrule"
    lines = ["% generated by scripts/make_report_tables.py -- do not edit by hand"]
    lines += [r"\newcommand{\MainTableRows}{", head]
    lines += [fmt_row(p, s.loc[p], best) for p in main_rows] + ["}"]
    lines += [r"\newcommand{\AblationTableRows}{", head]
    lines += [fmt_row(p, s.loc[p], {}) for p in abl_rows] + ["}"]

    def m(p, c):
        return s.loc[p, (c, "mean")]
    if {"ppo_v4", "threshold_tuned", "no_rebalancing"} <= set(s.index):
        km_cut = 100 * (1 - m("ppo_v4", "km") / m("threshold_tuned", "km"))
        lost_cut = 100 * (1 - m("ppo_v4", "lost") / m("no_rebalancing", "lost"))
        lost_cut_thr = 100 * (1 - m("ppo_v4", "lost") / m("threshold_tuned", "lost"))
        lines += [
            rf"\newcommand{{\KmCut}}{{{km_cut:.0f}}}",
            rf"\newcommand{{\LostCutVsNone}}{{{lost_cut:.0f}}}",
            rf"\newcommand{{\LostCutVsThr}}{{{lost_cut_thr:.0f}}}",
            rf"\newcommand{{\RetPPO}}{{{m('ppo_v4', 'ret'):.1f}}}",
            rf"\newcommand{{\RetThr}}{{{m('threshold_tuned', 'ret'):.1f}}}",
            rf"\newcommand{{\SrPPO}}{{{100 * m('ppo_v4', 'service_rate'):.1f}}}",
            rf"\newcommand{{\SrThr}}{{{100 * m('threshold_tuned', 'service_rate'):.1f}}}",
            rf"\newcommand{{\SrNone}}{{{100 * m('no_rebalancing', 'service_rate'):.1f}}}",
        ]
    ep = RES / "eval_episodes.csv"
    if ep.exists():
        raw = pd.read_csv(ep)
        e = raw.pivot(index="episode", columns="policy", values="ret")
        if {"ppo_v4", "threshold_tuned"} <= set(e.columns):
            lo = raw.pivot(index="episode", columns="policy", values="lost")
            dl = lo["threshold_tuned"] - lo["ppo_v4"]
            cil = 1.96 * dl.std(ddof=1) / len(dl) ** 0.5
            lines += [rf"\newcommand{{\PairedLost}}{{{dl.mean():.1f}}}",
                      rf"\newcommand{{\PairedLostCI}}{{{cil:.1f}}}",
                      rf"\newcommand{{\PairedLostWins}}{{{int((dl > 0).sum())}}}"]
            d = e["ppo_v4"] - e["threshold_tuned"]          # paired: same simulated day
            ci = 1.96 * d.std(ddof=1) / len(d) ** 0.5
            lines += [rf"\newcommand{{\PairedDiff}}{{{d.mean():+.1f}}}",
                      rf"\newcommand{{\PairedCI}}{{{ci:.1f}}}",
                      rf"\newcommand{{\PairedWins}}{{{int((d > 0).sum())}}}",
                      rf"\newcommand{{\PairedN}}{{{len(d)}}}"]
            print(f"[report] PPO - tuned threshold (paired): {d.mean():+.1f} ± {ci:.1f}, wins {int((d > 0).sum())}/{len(d)}")
    rob = RES / "robustness.csv"
    if rob.exists():
        r = pd.read_csv(rob).groupby(["policy", "scale"]).ret.mean().unstack(0)
        if {"ppo_v4", "threshold_tuned"} <= set(r.columns):
            gap = (r["ppo_v4"] - r["threshold_tuned"])
            lines.append(rf"\newcommand{{\RobGapHigh}}{{{gap.loc[gap.index.max()]:.1f}}}")
            lines.append(rf"\newcommand{{\RobScaleHigh}}{{{gap.index.max():.1f}}}")
            lines.append(rf"\newcommand{{\RobGapLow}}{{{gap.loc[gap.index.min()]:.1f}}}")
            lines.append(rf"\newcommand{{\RobGapOne}}{{{gap.loc[1.0]:.1f}}}")
            lines.append(rf"\newcommand{{\RobGapTwo}}{{{gap.loc[1.2]:.1f}}}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"[report] wrote {OUT}")


if __name__ == "__main__":
    main()
